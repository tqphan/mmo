//! Golden test vectors for the client's C# ports of `sim` (PLAN §10.4).
//!
//! The vectors are committed in `client/tests/vectors/` and checked by the client's tests. This
//! test fails when they're stale; `cargo xtask content` rewrites them (it sets `MMO_WRITE_VECTORS`).

use crate::cell::{self, CELL_SIZE_M, HYSTERESIS_M, OPEN_WORLD, WORLD_HALF_M};
use crate::ship;
use crate::terrain::{self, HeightFile};

const SIM_PATH: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/../../client/tests/vectors/sim.txt");

/// A float that C#'s `float.Parse` reads back to the same bits.
fn f(v: f32) -> String {
    if v.is_nan() {
        "NaN".into()
    } else if v.is_infinite() {
        if v > 0.0 { "Infinity".into() } else { "-Infinity".into() }
    } else {
        format!("{v:?}")
    }
}

/// A small deterministic generator, so the vectors only change when the rules do.
struct Lcg(u64);

impl Lcg {
    fn next(&mut self) -> f32 {
        self.0 = self.0.wrapping_mul(6364136223846793005).wrapping_add(1442695040888963407);
        (self.0 >> 40) as f32 / (1u64 << 24) as f32
    }

    fn range(&mut self, lo: f32, hi: f32) -> f32 {
        lo + (hi - lo) * self.next()
    }
}

pub fn generate() -> String {
    let mut out = String::from(
        "# Generated by sim (server/sim/src/vectors.rs). Do not edit; run `cargo xtask content`.\n\
         # cell_of <instance> <x> <z> <key>\n\
         # recenter <center> <x> <z> <margin> <key>\n\
         # window <center> <radius> <keys, comma-separated>\n\
         # yaw_to_u16 <radians> <wire>\n\
         # yaw_from_u16 <wire> <radians>\n\
         # mmoh <hex bytes of a height file>\n\
         # mmoh_sample <i> <j> <height>\n\
         # chunk_hash <cell key> <hash>, for each chunk of the mmoh file\n\
         # terrain_hash <hash of the whole mmoh file>\n\
         # ship_pose <x> <y> <z> <yaw> <local x> <y> <z> <world x> <y> <z>\n\
         # ship_step <hull> <x> <z> <yaw> <speed> <throttle> <rudder> <dt> <x> <z> <yaw> <speed>\n\
         # ship_sail <hull> <throttle> <rudder> <10 Hz steps from rest at the origin> <x> <z> <yaw> <speed>\n\
         # cannon_flight <x> <y> <z> <yaw> <pitch> <speed> <secs> <landing x> <landing z>, or none\n\
         # labor <points> <at> <now> <settled points> <settled at> <next regen at, or none>, with the content rules\n\
         # labor_spend <points> <at> <now> <cost> <points> <at>, or short <have>\n\
         # gather_reach <node x> <y> <z> <at x> <y> <z> <in reach: 1 or 0>\n\
         # gather_progress <node wire> <done at> <now> <progress>\n\
         # craft_reach <station x> <y> <z> <at x> <y> <z> <in reach: 1 or 0>\n\
         # craft_progress <recipe wire> <done at> <now> <progress>\n\
         # craft_affordable <recipe wire> <labor> <held of each input, in order> <units>\n\
         # land_mmoh <hex bytes of the height file the land_site vectors stand on>\n\
         # land_chunk <cell key> <hex of its 256 texels>; cells without one are wild\n\
         # land_snap <v> <snapped>\n\
         # land_site <plot wire> <x> <z> <other plots as wire:x:z, comma-separated, or -> <ok:lowest, or the error code>\n\
         # land_demolish_at <paid until> <demolish at>\n\
         # land_standing <paid until> <now> <standing: 0 paid, 1 overdue, 2 demolished> <can pay: 1 or 0>\n\
         # land_tax <plot wire> <plots owned> <seals a week, or none>\n\
         # farm_growth <crop wire> <ideal: 1 or 0> <from> <ripe at> <regrown at, or none> <withers at, or none>\n\
         # farm_stage <crop wire> <grown from> <ripe at> <now> <stage: 0 growing, 1 ripe, 2 withered> <progress>\n\
         # farm_spot <crop wire> <x> <z> <plots as x0:z0:x1:z1:tend, comma-separated, or -> <plantings as x:z:space, or -> <ok:y:plot index or -:ideal, or the error code>, on the land_ vectors' ground\n\
         # trade_reach <thing x y z> <at x y z> <1 or 0>\n\
         # trade_demand <permille> <at> <now> <demand now> <after a sale>\n\
         # trade_fresh <made at> <now> <permille, or spoiled>\n\
         # trade_quote <pack item wire> <origin x> <origin z> <made at> <post x> <post z> <bonus pct> <demand> <now> <route:demand:fresh:copper, or the error code>\n",
    );
    let mut rng = Lcg(0x6d6d6f);
    let edge = WORLD_HALF_M;
    let mut cell_of = |instance: u32, x: f32, z: f32| {
        out.push_str(&format!("cell_of {instance} {} {} {}\n", f(x), f(z), cell::cell_of(instance, x, z)));
    };
    for &(x, z) in &[
        (0.0, 0.0),
        (-0.01, -0.01),
        (64.0, 0.0),
        (63.999, 127.999),
        (-edge, -edge),
        (edge, edge),
        (edge - 0.001, -edge + 0.001),
        (1.0e9, -1.0e9),
        (f32::NAN, 5.0),
        (5.0, f32::INFINITY),
    ] {
        cell_of(OPEN_WORLD, x, z);
    }
    cell_of(7, 100.0, -100.0);
    for _ in 0..200 {
        let (x, z) = (rng.range(-8200.0, 8200.0), rng.range(-8200.0, 8200.0));
        cell_of(OPEN_WORLD, x, z);
    }

    // Around a few centres, positions spread over the cell, its margin and beyond.
    let centres = [
        cell::cell_of(OPEN_WORLD, 32.0, 32.0),
        cell::cell_of(OPEN_WORLD, -1000.0, 2500.0),
        cell::cell_of(OPEN_WORLD, edge - 1.0, -edge + 1.0),
        cell::cell_of(9, 0.0, 0.0),
    ];
    for &c in &centres {
        let (_, cy, cx) = cell::unpack(c);
        let lo_x = cx as f32 * CELL_SIZE_M - WORLD_HALF_M;
        let lo_z = cy as f32 * CELL_SIZE_M - WORLD_HALF_M;
        for _ in 0..60 {
            let x = lo_x + rng.range(-40.0, CELL_SIZE_M + 40.0);
            let z = lo_z + rng.range(-40.0, CELL_SIZE_M + 40.0);
            let r = cell::recenter(c, x, z, HYSTERESIS_M);
            out.push_str(&format!("recenter {c} {} {} {} {r}\n", f(x), f(z), f(HYSTERESIS_M)));
        }
        // Exactly on the margin's edges, and bad input.
        for (x, z) in [
            (lo_x - HYSTERESIS_M, lo_z),
            (lo_x + CELL_SIZE_M + HYSTERESIS_M, lo_z),
            (lo_x, lo_z - HYSTERESIS_M - 0.001),
            (f32::NAN, lo_z),
            (lo_x, f32::NEG_INFINITY),
        ] {
            let r = cell::recenter(c, x, z, HYSTERESIS_M);
            out.push_str(&format!("recenter {c} {} {} {} {r}\n", f(x), f(z), f(HYSTERESIS_M)));
        }
        for radius in [0u16, 1, 2, 4] {
            let keys: Vec<String> = cell::window_cells(c, radius).iter().map(u64::to_string).collect();
            out.push_str(&format!("window {c} {radius} {}\n", keys.join(",")));
        }
    }
    for c in [cell::pack(0, 0, 0), cell::pack(0, 249, 249), cell::pack(0, 0, 125)] {
        let keys: Vec<String> = cell::window_cells(c, 2).iter().map(u64::to_string).collect();
        out.push_str(&format!("window {c} 2 {}\n", keys.join(",")));
    }

    for yaw in [0.0, 0.5, -0.5, std::f32::consts::PI, -std::f32::consts::PI, 6.3, 100.0, -100.0] {
        out.push_str(&format!("yaw_to_u16 {} {}\n", f(yaw), ship::yaw_to_u16(yaw)));
    }
    for _ in 0..40 {
        let yaw = rng.range(-20.0, 20.0);
        out.push_str(&format!("yaw_to_u16 {} {}\n", f(yaw), ship::yaw_to_u16(yaw)));
    }
    for wire in [0u16, 1, 16384, 32768, 49152, 65535] {
        out.push_str(&format!("yaw_from_u16 {wire} {}\n", f(ship::yaw_from_u16(wire))));
    }

    // A 2 × 1 cell height file and some of its samples, for the client's .mmoh reader.
    let file = HeightFile::generate(3, 5, 2, 1, |x, z| (x * 0.37).sin() * 30.0 + z * 0.01);
    let hex: String = file.to_bytes().iter().map(|b| format!("{b:02x}")).collect();
    out.push_str(&format!("mmoh {hex}\n"));
    let (w, h) = file.size();
    for _ in 0..40 {
        let (i, j) = ((rng.next() * w as f32) as usize % w, (rng.next() * h as f32) as usize % h);
        out.push_str(&format!("mmoh_sample {i} {j} {}\n", f(terrain::decode(file.samples[j * w + i]))));
    }
    let chunks = file.chunks();
    for (cell, samples) in &chunks {
        out.push_str(&format!("chunk_hash {cell} {}\n", terrain::chunk_hash(*cell, samples)));
    }
    let total = terrain::terrain_hash(chunks.iter().map(|(c, s)| (*c, s.as_slice())));
    out.push_str(&format!("terrain_hash {total}\n"));
    ships(&mut out, &mut rng);
    labor(&mut out, &mut rng);
    gather(&mut out, &mut rng);
    craft(&mut out, &mut rng);
    land(&mut out, &mut rng);
    trade(&mut out, &mut rng);
    out
}

/// `sim::trade`'s reach, demand, freshness and quotes, for the client's port.
fn trade(out: &mut String, rng: &mut Lcg) {
    use crate::trade::{PACKS, TRADE, after_sale, demand_now, fresh_permille, in_reach, quote};
    let h: i64 = 3_600_000_000;
    for k in 0..40 {
        let at = [rng.range(-8000.0, 8000.0), rng.range(-5.0, 200.0), rng.range(-8000.0, 8000.0)];
        let spread = if k % 2 == 0 { TRADE.reach_m * 1.05 } else { TRADE.reach_m * 3.0 };
        let me = [at[0] + rng.range(-spread, spread), at[1] + rng.range(-spread, spread), at[2] + rng.range(-spread, spread)];
        let hit = u8::from(in_reach(at, me));
        out.push_str(&format!("trade_reach {} {} {} {} {} {} {hit}\n", f(at[0]), f(at[1]), f(at[2]), f(me[0]), f(me[1]), f(me[2])));
    }
    let t0: i64 = 1_800_000_000_000_000;
    for _ in 0..40 {
        let permille = (rng.next() * 1000.0) as u32;
        let now = t0 + ((rng.next() - 0.1) * 12.0 * h as f32) as i64;
        let d = demand_now(permille, t0, now);
        out.push_str(&format!("trade_demand {permille} {t0} {now} {d} {}\n", after_sale(d)));
    }
    let life = i64::from(TRADE.expire_s) * 1_000_000;
    for k in 0..40 {
        let now = match k {
            0 => t0,
            1 => t0 + i64::from(TRADE.fresh_s) * 1_000_000,
            2 => t0 + life,
            3 => t0 + life - 1,
            _ => t0 + ((rng.next() * 1.1 - 0.02) as f64 * life as f64) as i64,
        };
        let text = fresh_permille(t0, now).map_or("spoiled".to_string(), |p| p.to_string());
        out.push_str(&format!("trade_fresh {t0} {now} {text}\n"));
    }
    let mut codes = [0usize; 4];
    for k in 0..120 {
        let def = if k % 17 == 0 { 1 } else { PACKS[k % PACKS.len()].item };
        let origin = [rng.range(-8000.0, 8000.0), rng.range(-8000.0, 8000.0)];
        let reach = [0.6, 3.0, 12.0][k % 3] * 1000.0;
        let post = [origin[0] + rng.range(-reach, reach), origin[1] + rng.range(-reach, reach)];
        let bonus = [0, 20, 35][k % 3];
        let demand = 400 + (rng.next() * 600.0) as u32;
        let now = t0 + ((rng.next() * 1.2) as f64 * life as f64) as i64;
        let text = match quote(def, origin, t0, post, bonus, demand, now) {
            Ok(q) => {
                codes[0] += 1;
                format!("{}:{}:{}:{}", q.route_pct, q.demand, q.fresh, q.copper)
            }
            Err(e) => {
                codes[e as usize] += 1;
                (e as u8).to_string()
            }
        };
        out.push_str(&format!(
            "trade_quote {def} {} {} {t0} {} {} {bonus} {demand} {now} {text}\n",
            f(origin[0]),
            f(origin[1]),
            f(post[0]),
            f(post[1])
        ));
    }
    assert!(codes.iter().all(|&n| n > 0), "every quote result is covered: {codes:?}");
}

/// `sim::land`'s site checks, demolition time, standing and tax, for the client's port.
fn land(out: &mut String, rng: &mut Lcg) {
    use crate::land::{PLOTS, Rect, can_pay, check_site, demolish_at, snap, standing, weekly_tax, week_micros, LAND_CHUNK_LEN, max_plots};
    use std::collections::HashMap;
    // 2 × 2 cells from the origin: a gentle swell, a steep knoll at (90, 30) and a dip into the sea
    // at (30, 100).
    let file = HeightFile::generate(125, 125, 2, 2, |x, z| {
        let knoll = 6.0 * (-((x - 90.0).powi(2) + (z - 30.0).powi(2)) / 40.0).exp();
        let dip = 5.0 * (-((x - 30.0).powi(2) + (z - 100.0).powi(2)) / 300.0).exp();
        3.0 + 1.5 * (x * 0.05).sin() * (z * 0.07).cos() + knoll - dip
    });
    let hex: String = file.to_bytes().iter().map(|b| format!("{b:02x}")).collect();
    out.push_str(&format!("land_mmoh {hex}\n"));
    // Housing everywhere but a town strip at x 40–48 m, a wild hole and the far cell, with climates mixed in.
    let mut land: HashMap<u64, Vec<u8>> = HashMap::new();
    for (cx, cz) in [(125u16, 125u16), (126, 125), (125, 126)] {
        let mut t = vec![0u8; LAND_CHUNK_LEN];
        for (k, v) in t.iter_mut().enumerate() {
            let x = (cx as f32 - 125.0) * CELL_SIZE_M + (k % 16) as f32 * 4.0;
            let z = (cz as f32 - 125.0) * CELL_SIZE_M + (k / 16) as f32 * 4.0;
            let class = if (40.0..48.0).contains(&x) { 2 } else if (x, z) == (20.0, 80.0) { 0 } else { 1 };
            *v = class | ((k as u8 / 7) % 4) << 4;
        }
        let cell = cell::pack(OPEN_WORLD, cz, cx);
        let hex: String = t.iter().map(|b| format!("{b:02x}")).collect();
        out.push_str(&format!("land_chunk {cell} {hex}\n"));
        land.insert(cell, t);
    }
    for v in [0.0, 0.9, 1.0, 1.1, -1.0, -3.2, 7.0, 63.3, -8000.0] {
        out.push_str(&format!("land_snap {} {}\n", f(v), f(snap(v))));
    }
    let mut heights = terrain::FileChunks::new(&file);
    let mut codes = [0usize; 7];
    for k in 0..400 {
        let kind = &PLOTS[k % PLOTS.len()];
        let (x, z) = match k {
            0 => (WORLD_HALF_M - 2.0, 0.0),
            1 => (0.0, -WORLD_HALF_M + 6.0),
            _ => (snap(rng.range(2.0, 126.0)), snap(rng.range(2.0, 126.0))),
        };
        let pick = |rng: &mut Lcg| (rng.next() * PLOTS.len() as f32) as u8 % PLOTS.len() as u8;
        let others: Vec<(u8, f32, f32)> =
            (0..(k % 3)).map(|_| (pick(rng), snap(x + rng.range(-16.0, 16.0)), snap(z + rng.range(-16.0, 16.0)))).collect();
        let rects = others.iter().map(|&(w, ox, oz)| Rect::plot(&PLOTS[usize::from(w)], ox, oz));
        let got = check_site(&mut land, &mut heights, kind, x, z, rects);
        let text = match got {
            Ok(lowest) => {
                codes[0] += 1;
                format!("ok:{}", f(lowest))
            }
            Err(e) => {
                codes[e as usize] += 1;
                (e as u8).to_string()
            }
        };
        let others_text = if others.is_empty() {
            "-".to_string()
        } else {
            others.iter().map(|(w, ox, oz)| format!("{w}:{}:{}", f(*ox), f(*oz))).collect::<Vec<_>>().join(",")
        };
        out.push_str(&format!("land_site {} {} {} {others_text} {text}\n", kind.wire, f(x), f(z)));
    }
    assert!(codes.iter().all(|&n| n > 0), "every site result is covered: {codes:?}");
    let t0: i64 = 1_800_000_000_000_000;
    for _ in 0..40 {
        let paid = t0 + (rng.next() * 30.0 * 86_400e6) as i64;
        out.push_str(&format!("land_demolish_at {paid} {}\n", demolish_at(paid)));
    }
    for _ in 0..60 {
        let paid = t0 + (rng.next() * 30.0 * 86_400e6) as i64;
        let now = paid + ((rng.next() - 0.5) * 12.0 * week_micros() as f32) as i64;
        out.push_str(&format!("land_standing {paid} {now} {} {}\n", standing(paid, now) as u8, u8::from(can_pay(paid, now))));
    }
    for kind in &PLOTS {
        for owned in 0..=max_plots() + 1 {
            let tax = weekly_tax(kind, owned).map_or("none".to_string(), |t| t.to_string());
            out.push_str(&format!("land_tax {} {owned} {tax}\n", kind.wire));
        }
    }
    farm(out, rng, &mut land, &mut heights);
}

/// `sim::farm`'s growth, stages and spot checks, for the client's port, on the land vectors' ground.
fn farm(out: &mut String, rng: &mut Lcg, land: &mut std::collections::HashMap<u64, Vec<u8>>, heights: &mut terrain::FileChunks) {
    use crate::farm::{CROPS, Planting, PlotSpot, check_spot, progress, regrown_at, ripe_at, stage, withers_at};
    use crate::land::Rect;
    let none = |v: Option<i64>| v.map_or("none".to_string(), |v| v.to_string());
    let t0: i64 = 1_800_000_000_000_000;
    for k in &CROPS {
        for ideal in [false, true] {
            let from = t0 + (rng.next() * 86_400e6) as i64;
            let ripe = ripe_at(k, from, ideal);
            out.push_str(&format!(
                "farm_growth {} {} {from} {ripe} {} {}\n",
                k.wire,
                u8::from(ideal),
                none(regrown_at(k, from, ideal)),
                none(withers_at(k, ripe))
            ));
            for _ in 0..4 {
                let span = (ripe - from) as f32 + k.wither_s as f32 * 1e6;
                let now = from + ((rng.next() * 1.4 - 0.1) * span) as i64;
                out.push_str(&format!("farm_stage {} {from} {ripe} {now} {} {}\n", k.wire, stage(k, ripe, now) as u8, f(progress(from, ripe, now))));
            }
        }
    }
    let mut codes = [0usize; 8];
    for n in 0..300 {
        let kind = &CROPS[n % CROPS.len()];
        let (x, z) = match n {
            0 => (WORLD_HALF_M, 0.0),
            _ => (rng.range(1.0, 140.0), rng.range(1.0, 127.0)),
        };
        // A plot that may cover the spot, and plantings around it.
        let plots: Vec<PlotSpot> = (0..(n % 3))
            .map(|_| {
                let (px, pz, h) = (x + rng.range(-12.0, 12.0), z + rng.range(-12.0, 12.0), [4.0, 8.0][(rng.next() * 2.0) as usize % 2]);
                PlotSpot { rect: Rect { x0: px - h, z0: pz - h, x1: px + h, z1: pz + h }, may_tend: rng.next() < 0.5 }
            })
            .collect();
        let others: Vec<Planting> =
            (0..(n % 4)).map(|_| Planting { x: x + rng.range(-4.0, 4.0), z: z + rng.range(-4.0, 4.0), space_m: [0.5, 1.5, 2.0][(rng.next() * 3.0) as usize % 3] }).collect();
        let text = match check_spot(land, heights, kind, x, z, &plots, others.iter().copied()) {
            Ok(s) => {
                codes[0] += 1;
                format!("ok:{}:{}:{}", f(s.y), s.plot.map_or("-".to_string(), |p| p.to_string()), u8::from(s.ideal))
            }
            Err(e) => {
                codes[e as usize] += 1;
                (e as u8).to_string()
            }
        };
        let list = |v: Vec<String>| if v.is_empty() { "-".to_string() } else { v.join(",") };
        let plots_text = list(plots.iter().map(|p| format!("{}:{}:{}:{}:{}", f(p.rect.x0), f(p.rect.z0), f(p.rect.x1), f(p.rect.z1), u8::from(p.may_tend))).collect());
        let others_text = list(others.iter().map(|o| format!("{}:{}:{}", f(o.x), f(o.z), f(o.space_m))).collect());
        out.push_str(&format!("farm_spot {} {} {} {plots_text} {others_text} {text}\n", kind.wire, f(x), f(z)));
    }
    assert!(codes.iter().all(|&n| n > 0), "every spot result is covered: {codes:?}");
}

/// `sim::craft`'s reach, progress and affordability, for the client's port.
fn craft(out: &mut String, rng: &mut Lcg) {
    use crate::craft::{CRAFT_REACH_M, RECIPES, affordable, craft_micros, in_reach, progress};
    for k in 0..80 {
        let st = [rng.range(-8000.0, 8000.0), rng.range(-5.0, 200.0), rng.range(-8000.0, 8000.0)];
        let spread = if k % 2 == 0 { CRAFT_REACH_M * 1.05 } else { CRAFT_REACH_M * 3.0 };
        let at = [st[0] + rng.range(-spread, spread), st[1] + rng.range(-spread, spread), st[2] + rng.range(-spread, spread)];
        let hit = u8::from(in_reach(st, at));
        out.push_str(&format!("craft_reach {} {} {} {} {} {} {hit}\n", f(st[0]), f(st[1]), f(st[2]), f(at[0]), f(at[1]), f(at[2])));
    }
    let t0: i64 = 1_800_000_000_000_000;
    for (k, r) in RECIPES.iter().enumerate() {
        let done = t0 + k as i64 + craft_micros(r);
        for _ in 0..4 {
            let now = done + ((rng.next() - 0.7) * 1.6 * r.craft_s * 1e6) as i64;
            out.push_str(&format!("craft_progress {} {done} {now} {}\n", r.wire, f(progress(r, done, now))));
        }
        for _ in 0..4 {
            let held: Vec<u32> = r.inputs.iter().map(|i| (rng.next() * 12.0 * i.count as f32) as u32).collect();
            let labor = (rng.next() * 12.0 * r.labor as f32) as i32 - r.labor;
            let have = |w: u16| r.inputs.iter().position(|i| i.item == w).map_or(0, |p| held[p]);
            let held_text: Vec<String> = held.iter().map(u32::to_string).collect();
            out.push_str(&format!("craft_affordable {} {labor} {} {}\n", r.wire, held_text.join(" "), affordable(r, have, labor)));
        }
    }
}

/// `sim::gather`'s reach and progress, for the client's port.
fn gather(out: &mut String, rng: &mut Lcg) {
    use crate::gather::{GATHER_REACH_M, NODES, done_at, in_reach, progress};
    for k in 0..80 {
        let node = [rng.range(-8000.0, 8000.0), rng.range(-5.0, 200.0), rng.range(-8000.0, 8000.0)];
        // Half near the edge of reach, where rounding would show.
        let spread = if k % 2 == 0 { GATHER_REACH_M * 1.05 } else { GATHER_REACH_M * 3.0 };
        let at = [node[0] + rng.range(-spread, spread), node[1] + rng.range(-spread, spread), node[2] + rng.range(-spread, spread)];
        let hit = u8::from(in_reach(node, at));
        out.push_str(&format!("gather_reach {} {} {} {} {} {} {hit}\n", f(node[0]), f(node[1]), f(node[2]), f(at[0]), f(at[1]), f(at[2])));
    }
    let t0: i64 = 1_800_000_000_000_000;
    for (k, n) in NODES.iter().enumerate() {
        let done = done_at(n, t0 + k as i64);
        for _ in 0..8 {
            let now = done + ((rng.next() - 0.7) * 1.6 * n.gather_s * 1e6) as i64;
            out.push_str(&format!("gather_progress {} {done} {now} {}\n", n.wire, f(progress(n, done, now))));
        }
    }
}

/// `sim::labor` with the content rules, for the client's port.
fn labor(out: &mut String, rng: &mut Lcg) {
    use crate::labor::{LABOR, Pool};
    let period = i64::from(LABOR.regen_period_s) * 1_000_000;
    let t0: i64 = 1_800_000_000_000_000;
    let cap = LABOR.cap;
    let mut pools = vec![
        (Pool { points: 0, at: t0 }, t0),
        (Pool { points: cap, at: t0 }, t0 + 5),
        (Pool { points: cap - 5, at: t0 }, t0 + period),
        (Pool { points: 100, at: t0 }, t0 + period - 1),
        (Pool { points: 100, at: t0 }, t0 - period),
        (Pool { points: 0, at: t0 }, i64::MAX),
        (Pool { points: cap + 100, at: t0 }, t0 + 3 * period),
    ];
    for _ in 0..60 {
        let points = (rng.next() * (cap + 1) as f32) as i32;
        let elapsed = (rng.next() as f64 * 40.0 * period as f64) as i64;
        pools.push((Pool { points, at: t0 }, t0 + elapsed));
    }
    for (p, now) in &pools {
        let s = p.settle(&LABOR, *now);
        let next = p.next_regen_at(&LABOR, *now).map_or("none".to_string(), |n| n.to_string());
        out.push_str(&format!("labor {} {} {now} {} {} {next}\n", p.points, p.at, s.points, s.at));
    }
    for (k, (p, now)) in pools.iter().enumerate() {
        let cost = match k % 4 {
            0 => 1,
            1 => p.current(&LABOR, *now) + 1,
            2 => 0,
            _ => (rng.next() * 300.0) as i32 + 1,
        };
        let line = format!("labor_spend {} {} {now} {cost}", p.points, p.at);
        match p.spend(&LABOR, *now, cost) {
            Ok(n) => out.push_str(&format!("{line} {} {}\n", n.points, n.at)),
            Err(e) => out.push_str(&format!("{line} short {}\n", e.have)),
        }
    }
}

/// `sim::ship`'s frames, step and cannon flight, for the client's port.
fn ships(out: &mut String, rng: &mut Lcg) {
    use ship::{Hull, Input, Motion, Pose};
    for _ in 0..30 {
        let pose = Pose { x: rng.range(-8000.0, 8000.0), y: rng.range(0.0, 4.0), z: rng.range(-8000.0, 8000.0), yaw: rng.range(-7.0, 7.0) };
        let l = [rng.range(-4.0, 4.0), rng.range(-2.0, 2.0), rng.range(-10.0, 10.0)];
        let w = pose.to_world(l);
        out.push_str(&format!(
            "ship_pose {} {} {} {} {} {} {} {} {} {}\n",
            f(pose.x), f(pose.y), f(pose.z), f(pose.yaw), f(l[0]), f(l[1]), f(l[2]), f(w[0]), f(w[1]), f(w[2])
        ));
    }
    let hull = Hull::Clipper;
    let input = |rng: &mut Lcg| {
        // Mostly the extremes and zero, which is where the step's branches are.
        let pick = |rng: &mut Lcg| match (rng.next() * 6.0) as i32 {
            0 => 0,
            1 => 100,
            2 => -100,
            _ => (rng.range(-100.0, 100.0)) as i8,
        };
        Input { throttle: pick(rng), rudder: pick(rng) }
    };
    for k in 0..200 {
        let speed = match k % 5 {
            0 => 0.0,
            1 => hull.data().max_speed_mps,
            _ => rng.range(-4.0, 12.0),
        };
        let m = Motion { x: rng.range(-8000.0, 8000.0), z: rng.range(-8000.0, 8000.0), yaw: rng.range(0.0, std::f32::consts::TAU), speed };
        let i = input(rng);
        let dt = if k % 3 == 0 { 0.1 } else { rng.range(0.0, 0.25) };
        let n = ship::step(m, hull.data(), i, dt);
        out.push_str(&format!(
            "ship_step {} {} {} {} {} {} {} {} {} {} {} {}\n",
            hull as u8, f(m.x), f(m.z), f(m.yaw), f(m.speed), i.throttle, i.rudder, f(dt), f(n.x), f(n.z), f(n.yaw), f(n.speed)
        ));
    }
    for (throttle, rudder, steps) in [(100, 0, 150), (100, 100, 400), (60, -40, 300), (-100, 50, 100), (0, 100, 50), (100, 7, 600)] {
        let i = Input { throttle, rudder };
        let mut m = Motion { x: 0.0, z: 0.0, yaw: 0.0, speed: 0.0 };
        for _ in 0..steps {
            m = ship::step(m, hull.data(), i, 0.1);
        }
        out.push_str(&format!("ship_sail {} {throttle} {rudder} {steps} {} {} {} {}\n", hull as u8, f(m.x), f(m.z), f(m.yaw), f(m.speed)));
    }
    let c = &hull.data().cannon;
    for k in 0..40 {
        let from = [rng.range(-8000.0, 8000.0), if k == 0 { 0.0 } else { rng.range(0.5, 5.0) }, rng.range(-8000.0, 8000.0)];
        let (yaw, pitch) = (rng.range(-7.0, 7.0), rng.range(c.min_pitch_deg, c.max_pitch_deg).to_radians());
        let line = format!("cannon_flight {} {} {} {} {} {}", f(from[0]), f(from[1]), f(from[2]), f(yaw), f(pitch), f(c.muzzle_speed_mps));
        match ship::cannon_flight(from, yaw, pitch, c.muzzle_speed_mps) {
            Some(fl) => out.push_str(&format!("{line} {} {} {}\n", f(fl.secs), f(fl.landing[0]), f(fl.landing[2]))),
            None => out.push_str(&format!("{line} none\n")),
        }
    }
}

#[test]
fn client_vectors_are_current() {
    let fresh = generate();
    if std::env::var_os("MMO_WRITE_VECTORS").is_some() {
        std::fs::create_dir_all(std::path::Path::new(SIM_PATH).parent().unwrap()).unwrap();
        std::fs::write(SIM_PATH, &fresh).unwrap();
        return;
    }
    let committed = std::fs::read_to_string(SIM_PATH).unwrap_or_default().replace("\r\n", "\n");
    assert!(committed == fresh, "client/tests/vectors/sim.txt is stale; run `cargo xtask content`");
}
